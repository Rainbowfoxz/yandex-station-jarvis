#!/bin/sh
# Отдаёт в stdout куски /tmp/jarvis/<n>.raw по порядку, начиная с самого свежего (запускается по SSH).
# Выходит, как только читатель ушёл (cat не смог записать): иначе после обрыва SSH копии копятся
# и забивают процессор колонки — поток начинает отставать на секунды.
D=/tmp/jarvis
last() { ls $D 2>/dev/null | grep '\.raw$' | sed 's/\.raw$//' | sort -n | tail -1; }
i=$(last)
[ -n "$i" ] || i=0
miss=0
while :; do
  if [ -f $D/$i.raw ]; then
    cat $D/$i.raw || exit 0
    i=$((i + 1))
    miss=0
    continue
  fi
  usleep 20000
  miss=$((miss + 1))
  # Тяжёлая проверка (5 процессов) — раз в ~0,6 с без нового куска, а не на каждом опросе:
  # отстали дальше, чем хранит приёмник, или приёмник начал счёт заново — прыгаем к свежему.
  if [ $miss -ge 30 ]; then
    miss=0
    l=$(last)
    if [ -n "$l" ] && { [ "$l" -gt "$i" ] || [ "$l" -lt $((i - 1)) ]; }; then
      i=$l
    fi
  fi
done
